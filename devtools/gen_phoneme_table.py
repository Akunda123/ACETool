# 由官方 ACE_phonemes 的 mapping 表生成 internal/phoneme/table.go
#
# 输入：internal/phoneme/source/phoneme_mapping.md（官方仓 timedomain-tech/ACE_phonemes）
# 输出：internal/phoneme/table.go（含 IPA、官方四分类、按 IPA 推出的发音方式、示例）
#
# 示例来源优先级：
#   ① SV 官方音素表里**同符号**的例词（英文 ARPABET 与 ACE 基本同名，命中率最高）
#   ② 没有就留空（面板会退回显示“该音符自己的字”作上下文）
import io
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'internal', 'phoneme', 'source', 'phoneme_mapping.md')
OUT = os.path.join(ROOT, 'internal', 'phoneme', 'table.go')
SV_TABLE = os.path.join(os.path.expanduser('~'), 'Documents', 'SVAgent', 'dist', 'knowledge', 'docs', '音素表.json')

SECTION_LANG = {
    'English Phoneme Mapping': 'eng',
    'Spanish Phoneme Mapping': 'spa',
    'Chinese Phoneme Mapping': 'zh',
    'Japanese Phoneme Mapping': 'jp',
}

# IPA → 发音方式（只按 ACA 侧需要的粒度）
MANNER = [
    (r'^[pbt d k g ʔ]$'.replace(' ', ''), '塞音'),
    (r'^(tʃ|dʒ|ts|dz|tɕ|dʑ|tr|dr|pf)$', '塞擦音'),
    (r'^(f|v|s|z|ʃ|ʒ|θ|ð|x|ɣ|ç|h|ɸ|β)$', '擦音'),
    (r'^(m|n|ŋ|ɲ|ɳ|m̩|n̩|ŋ̍)$', '鼻音'),
    (r'^(l|ɫ|ɭ)$', '边音'),
    (r'^(r|ʀ|ʁ)$', '颤音/擦音'),
    (r'^(ɾ|ɽ)$', '闪音'),
    (r'^(j|w|ɥ|ɹ|ɻ|ʋ|ɰ)$', '近音'),
]
VOWEL = '元音'


def manner_of(ipa: str, cls: str) -> str:
    ipa = ipa.strip()
    if cls.lower().startswith('vowel'):
        return VOWEL
    for pat, name in MANNER:
        if re.match(pat, ipa):
            return name
    if 'vocalic' in cls.lower():
        return '成音节辅音'
    return ''


def parse_mapping(path):
    rows = {}
    lang = None
    for line in io.open(path, encoding='utf-8'):
        m = re.match(r'^##\s+(.+?)\s*$', line)
        if m:
            title = m.group(1).strip()
            lang = SECTION_LANG.get(title)
            if lang and lang not in rows:
                rows[lang] = []
            continue
        if not lang:
            continue
        m = re.match(r'^\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*$', line)
        if not m:
            continue
        sym, ipa, cls = m.group(1).strip(), m.group(2).strip(), m.group(3).strip()
        if sym.lower() in ('ace phoneme', '---') or set(sym) <= set('-: '):
            continue
        rows[lang].append({'sym': sym, 'ipa': ipa, 'cls': cls})
    return rows


def load_sv_examples():
    """SV 音素表：符号 → 例词（英文 ARPABET 与 ACE 同名，直接可用）。"""
    out = {}
    try:
        j = json.load(io.open(SV_TABLE, encoding='utf-8'))
    except Exception:
        return out
    for t in j.get('tables', []):
        lang = (t.get('language') or '').lower()
        for g in t.get('groups', []):
            for r in g.get('rows', []):
                p, ex = (r.get('phoneme') or '').strip(), (r.get('example') or '').strip()
                if p and ex and p not in out:
                    out[p] = ex
    return out


def main():
    rows = parse_mapping(SRC)
    sv = load_sv_examples()
    parts = ['''// Code generated by devtools/gen_phoneme_table.py; DO NOT EDIT.
//
// 数据源：官方仓 timedomain-tech/ACE_phonemes 的 phoneme_mapping.md
//   · IPA 与四分类（Vowel / Semivowel / Consonant / Vocalic Consonant）来自官方表；
//   · 「发音方式」由 IPA 推断（塞音/擦音/塞擦音/鼻音/边音/近音/颤音/闪音/元音）；
//   · 示例优先取 SV 官方音素表里同符号的例词，没有则为空串。
package phoneme

// Entry 是一个音素的展示与分类信息。
type Entry struct {
	Symbol   string // ACE 音素符号（写回用的裸 token）
	IPA      string
	Official string // 官方四分类
	Manner   string // 由 IPA 推断的发音方式
	Example  string // 例词（可能为空）
}

// Table 是「语言 → 音素符号 → 信息」。语言键与 CLI 的 `phoneme inventory --language` 对应：
// zh / jp / eng / spa（ACE 用全名，如 Chinese）。
var Table = map[string]map[string]Entry{
''' ]
    for lang, items in rows.items():
        parts.append('\t"%s": {\n' % lang)
        for it in items:
            ex = sv.get(it['sym'], '')
            key = json.dumps(it['sym'], ensure_ascii=False)
            parts.append('\t\t' + key + ': {Symbol: ' + key
                         + ', IPA: ' + json.dumps(it['ipa'], ensure_ascii=False)
                         + ', Official: ' + json.dumps(it['cls'], ensure_ascii=False)
                         + ', Manner: ' + json.dumps(manner_of(it['ipa'], it['cls']), ensure_ascii=False)
                         + ', Example: ' + json.dumps(ex, ensure_ascii=False) + '},\n')
        parts.append('\t},\n')
    parts.append('}\n')
    io.open(OUT, 'w', encoding='utf-8', newline='\n').write(''.join(parts))
    total = sum(len(v) for v in rows.values())
    print('languages:', {k: len(v) for k, v in rows.items()})
    print('total entries:', total, '→', OUT)
    with_ex = sum(1 for v in rows.values() for it in v if sv.get(it['sym']))
    print('有例词:', with_ex)


if __name__ == '__main__':
    main()
